def seed_open_data_tasks() -> int:
    """Add missing educational briefs without overwriting any existing records."""
    init_db()
    inserted = 0
    with closing(connect()) as connection, connection:
        connection.execute("BEGIN IMMEDIATE")
        for task in OPEN_DATA_TASKS:
            marker = task["context"].split(". ", 1)[0] + "."
            if connection.execute(
                "SELECT 1 FROM tasks WHERE owner_user_id IS NULL AND (title = ? OR instr(context, ?) = 1)",
                (task["title"], marker),
            ).fetchone():
                continue
            cursor = connection.execute(
                f"INSERT INTO tasks ({', '.join(EDITABLE_FIELDS)}, status, confirmed_at) VALUES ({', '.join('?' for _ in EDITABLE_FIELDS)}, 'published', ?)",
                tuple(task.get(field, "") for field in EDITABLE_FIELDS) + (datetime.now(timezone.utc).isoformat(),),
            )
            recalculate_task(connection, cursor.lastrowid)
            inserted += 1
    return inserted


if __name__ == "__main__":
    print(f"Добавлено учебных кейсов на открытых данных: {seed_open_data_tasks()}")
